import io
p = 'docs/military-marriage-power.md'
s = io.open(p, encoding='utf-8').read()

add = '''

---

# 第三部分 · 上线纪律（不许抢戏）

> 这一部分不是功能，是**约束**。违反它，前面所有系统都会被玩家骂成"查账机器人"。

## 一、三条隔离规则

### ① 静默运行

```
钱庄挤兑 / 盐价涨 / 码头械斗 / 粮价波动 / 党争推进
→ 全部在世界 tick 里算
→ 不进对话、不弹窗、不打断、不主动播报
```

**世界照常运转，玩家不问，就不说。**

### ② 只在相关时露一句

```
触发条件 = 话题命中 且 在场者相关
```

| 玩家在聊 | 可注入 | 不可注入 |
|---|---|---|
| "这银子哪来的" | 钱庄、铺子进项 | 盐引、党争 |
| 跟盐商谈买卖 | 盐引价、私盐风险 | 粮价、码头抽成 |
| 跟她调情 | **什么都不注入** | 任何账目 |
| 跟官场人吃饭 | 派系、弹劾风险 | 铺子流水 |
| 行军 / 攻城 | 军饷、粮草 | 钱庄存银 |

### ③ 默认沉默，最多三条

```
每轮注入的事实 ≤ 3 条
没有触发词 → 0 条
宁可少说，不可多说
```

## 二、四条"不许"

```
❌ 不许 NPC 主动报账（"妾身瞧过账本，今日进项……"）
❌ 不许把数值念出来（"你的信任度是 62"）
❌ 不许在亲密/争吵/劝和场景里提钱
❌ 不许用账本事实盖掉她的情绪（她想吃醋就吃醋，别用"账上没这笔"堵回去）
```

## 三、账号隔离（双真人）

```
紫嫣的账号里，不许出现"王家的账"细节
她的账号只看到：她自己的铺子、她自己的人、她自己听到的传闻
```

**同一个世界，不同的人知道的不一样。** 这是真实感的核心。

## 四、成本与延迟

```
金融/军法/党争 全部本地计算，不增加任何 LLM 调用
注入只在拼提示词时做字符串筛选
```

**不许因为这些系统，让每轮对话多一次模型调用。**

## 五、验收（量化）

```
① 跟她闲聊 10 轮：她主动提钱/账/盐/官场 ≤ 1 次
② 调情场景：账本注入 0 条
③ 问"银子哪来的"：能答，且只提 1~2 条相关
④ 双端：她的账号看不到王家细账
⑤ 延迟：注入前后，单轮耗时差 < 100ms
```

**第 ① 条不过，就是抢戏，必须收紧。**

## 六、一句话

```
账在后台走，情在台前演。
世界可以很复杂，但她开口时，只说她此刻该说的话。
```
'''

if '第三部分 · 上线纪律' not in s:
    io.open(p, 'w', encoding='utf-8').write(s.rstrip() + add)
    print('appended discipline section')
else:
    print('already exists')
