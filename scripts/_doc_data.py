import io
p = 'docs/cost-optimization.md'
s = io.open(p, encoding='utf-8').read()

add = '''

---

# 附：数据会长多大，怎么自动备份

## 一、先说结论

```
真正会撑爆的不是 state.json（一年也就几百 KB）
是 ① 语音 wav 文件  ② 聊天历史
```

**state 是"账本"，很轻；音频和对话是"录音带"，很重。**

## 二、实测与估算

### 现在（第 15 日，150+ 人物）

| 文件 | 大小 | 说明 |
|---|---|---|
| `state.json` | ~95 KB（本地实测） | 150 人、关系网、产业、案子 |
| `history-*.json` | 4~35 KB / 人 | 每轮约 0.3~0.5 KB |
| `*.wav` | 20~60 KB / 条 | 每条语音一个文件 |
| `milestones.json` | 2 KB | 大事记 |

### 一年后会怎样

| 项目 | 增长估算 | 一年后 | 处理 |
|---|---|---|---|
| `state.json` | +5~10 KB/日 | **300~600 KB** | 不用管 |
| `events.jsonl` | 30 条/日 × 300 B | **3 MB** | 按月切分压缩 |
| 聊天历史（4 人） | 100 轮/日 × 0.5 KB | **~70 MB** | 按月归档 + gzip（压到 ~7 MB） |
| **语音 wav** | 100 条/日 × 40 KB | **~1.4 GB** | **保留 7 天，其余删或转码** |
| 每日快照 | 300 KB × 23 份 | **~7 MB** | 三级保留 |

**结论：一年总量可控在 50 MB 以内——前提是音频有保留策略。**

## 三、四个"自家能解决"的办法

### ① 音频：保留 7 天，超期删

```
data/audio/*.wav  → 只留最近 7 天
更早的：删掉（需要时重新合成）
或转 mp3（体积压到 1/10）
```

**这一条就能把 1.4 GB 压到 30 MB 左右。**

### ② 聊天历史：按月切分 + 压缩

```
history-husband.json → history-husband-2026-11.json.gz
保留最近 3 个月原文，更早的压成摘要（每 50 轮一条）
```

### ③ 快照：三级保留

```
每日 1 份，保留 7 天
每周 1 份，保留 4 周
每月 1 份，保留 12 月
超出自动删最旧的
```

### ④ state 自己瘦身

```
appliedActions：只留最近 500 条（已有 prune）
memories：上限 500 条，超了按时间淘汰
bonds：只留 |score| ≥ 15（已有）
events：只留最近 30 天进 state，其余进 jsonl
```

## 四、自动备份（不需要人管）

### 方案：每日一次，本地 + 异地

```
每天 03:00
  ① 打包：state.json + events + 历史 + 快照索引 → backup-YYYYMMDD.tar.gz
  ② 存本地：/opt/familysoul/backups/（保留 14 天）
  ③ 推到异地：192.168.1.112（开发机）或你的网盘
  ④ 每周日：把最新一份再存一份到"周备份"（保留 8 周）
```

**用 systemd timer 或 crontab 都行，一条命令的事。**

### 恢复演练（每季度一次）

```
拿一份周备份 → 在临时目录解包 → 起服务 → 确认世界能读
```

**没演练过的备份，等于没有备份。**

### 体积控制

```
tar.gz 压缩后，state+events+history 约 1~5 MB/天
14 天 ≈ 20~70 MB
加周备份 8 份 ≈ 再加 40 MB
总占用 < 150 MB
```

## 五、一句话

```
数据不是"会爆炸"，是"没人管就会慢慢堆"。
设好保留期，它自己就稳了。
```

**三件事必须做：音频 7 天、历史按月压、快照三级留。**

## 六、验收

```
① 跑 30 天后，data/ 总量 < 100 MB
② 随机抽一份 7 天前的备份，能恢复
③ 删音频后，旧对话仍能正常显示文字
④ 快照只留规定份数，不会无限涨
```
'''

if '数据会长多大' not in s:
    io.open(p, 'w', encoding='utf-8').write(s.rstrip() + add)
    print('appended data/backup section')
else:
    print('exists')
